"""Небольшие помощники сопоставления текста, общие для скоринга, генерации и защит.

Сопоставление подстрок намеренно не используется для коротких терминов. Без
границ слова навык ``бот`` совпадает с ``работа`` и ``обработка``, что молча
поднимает несвязанные заказы на верх очереди.

Русские термины сопоставляются по основе: ``сайт`` находит ``сайта``,
``сайтов`` и ``сайтами``, ``дизайн`` — ``дизайнера``, ``верстка`` —
``верстки``. Раньше отсекалась только последняя буква, поэтому короткие
слова в падежах не совпадали, и заказы вроде «Создание сайта» оставались
без рубрики и не доходили до пользователя.
"""

from __future__ import annotations

import re
from functools import lru_cache

_WORD_CHARS = "0-9a-zа-яё"

_CONTACT_RE = re.compile(
    r"(?i)(?:"
    r"(?:телеграм|telegram|whatsapp|ватсап|viber|вайбер|skype|скайп)\s*[:@]\s*\S+"
    r"|(?:https?://)?t\.me/\S+"
    r"|@\w{4,}"
    r"|[\w.+-]+@[\w-]+\.[\w.]+"
    r")"
)

#: Падежные окончания, которые срезаются с основы слова. Список сортируется
#: по длине при первом использовании: «ами» должно срезаться раньше «и».
_RU_ENDINGS: tuple[str, ...] = tuple(
    sorted(
        (
            "ами",
            "ями",
            "ого",
            "его",
            "ому",
            "ему",
            "ыми",
            "ими",
            "ьей",
            "ьям",
            "ьях",
            "ей",
            "ой",
            "ый",
            "ий",
            "ая",
            "яя",
            "ое",
            "ее",
            "ые",
            "ие",
            "ых",
            "их",
            "ым",
            "им",
            "ом",
            "ем",
            "ам",
            "ям",
            "ах",
            "ях",
            "ов",
            "ев",
            "ью",
            "ия",
            "ие",
            "ии",
            "а",
            "я",
            "о",
            "е",
            "у",
            "ю",
            "ы",
            "и",
            "ь",
            "й",
        ),
        key=len,
        reverse=True,
    )
)

#: Минимальная длина основы: короче — слово считается коротким и получает
#: узкое окно окончаний, чтобы «бот» не цеплял «ботаник», а «тест» — «тесный».
_MIN_STEM = 3

#: Окончание-хвост после основы: сколько букв ещё может нарасти. Длинные
#: хвосты нужны для словообразований («тест» → «тестирование»), короткие —
#: для трёхбуквенных основ.
_TAIL_LONG = 7
_TAIL_SHORT = 3
_SHORT_STEM = 4


def strip_contact_handles(text: str) -> str:
    """Удаляет ники мессенджеров и ссылки, чтобы они не выглядели как совпадение навыка.
    """
    return re.sub(r"\s+", " ", _CONTACT_RE.sub(" ", text)).strip()


def _normalise(text: str) -> str:
    return text.lower().replace("ё", "е")


def _stem(word: str) -> str:
    """Отрезает падежное окончание от русского слова.

    Слово без окончания возвращается как есть: ``сайт`` → ``сайт``,
    ``сайтами`` → ``сайт``, ``верстки`` → ``верстк``.
    """
    return next(
        (word[: -len(ending)] for ending in _RU_ENDINGS
         if len(word) - len(ending) >= _MIN_STEM and word.endswith(ending)),
        word,
    )


@lru_cache(maxsize=8192)
def _term_pattern(needle: str) -> re.Pattern[str]:
    """Собирает регулярное выражение для термина с учётом словоформ.

    Каждое слово термина приводится к основе, после которой допускается
    хвост окончания. Границы слова остаются обязательными: совпадение
    внутри другого слова по-прежнему запрещено.
    """
    parts: list[str] = []
    # Дефис разделяет слова так же, как пробел: «сайт-визитка», «сайт визитка»
    # и «сайта-визитки» — одна и та же фраза. Без этого дефисное слово
    # считалось единым токеном и не совпадало ни с одной словоформой.
    tokens = [token for token in re.split(r"[\s\-]+", _normalise(needle)) if token]
    for word in tokens:
        if re.search(r"[а-я]", word):
            stem = _stem(word)
            tail = _TAIL_SHORT if len(stem) < _SHORT_STEM else _TAIL_LONG
            parts.append(re.escape(stem) + rf"[а-я]{{0,{tail}}}")
        else:
            # Латиница и цифры: точное совпадение плюс простое множественное.
            parts.append(re.escape(word) + r"s?")
    body = r"[\s\-]+".join(parts)
    return re.compile(rf"(?<![{_WORD_CHARS}]){body}(?![{_WORD_CHARS}])")


def contains_term(text: str, term: str) -> bool:
    """Возвращает True, если *term* встречается как отдельное слово или фраза.

        Русские термины сопоставляются по основе, поэтому ``сайт`` находит
        ``сайта`` и ``сайтами``, а ``автоматизация`` — ``автоматизации``.
        Границы слова обязательны: ``бот`` не совпадает с ``работа``.
    """
    needle = term.strip()
    if not needle:
        return False
    return _term_pattern(needle).search(_normalise(text)) is not None


def matching_terms(text: str, terms: list[str]) -> list[str]:
    """Возвращает все термины из *terms*, найденные в *text*, сохраняя порядок ввода.
    """
    return [term for term in terms if contains_term(text, term)]


#: Сокращения, после которых точка не заканчивает предложение.
_ABBREVIATIONS = (
    "см",
    "т",
    "е",
    "др",
    "пр",
    "г",
    "гг",
    "руб",
    "тыс",
    "млн",
    "им",
    "ул",
    "д",
    "кв",
    "стр",
    "рис",
    "табл",
    "напр",
    "т.п",
    "т.д",
    "т.к",
    "т.н",
    "т.ч",
    "т.о",
    "p.s",
    "ps",
)


def _mask_abbreviations(text: str) -> str:
    """Заменяет точку в сокращениях маркером, чтобы деление не рвало фразу.

    Составные сокращения («т. к.», «т. е.») обрабатываются первыми: иначе
    «т. к.» распалось бы на два односимвольных обрывка.
    """
    masked = re.sub(
        r"\b([а-яёa-z])\.\s*([а-яёa-z])\.\s*(?=[а-яёa-z])",
        r"\1<DOT>\2<DOT> ",
        text,
        flags=re.IGNORECASE,
    )
    masked = re.sub(
        r"\b([а-яё])\.([а-яё])\.",
        r"\1<DOT>\2<DOT>",
        masked,
        flags=re.IGNORECASE,
    )
    return re.sub(
        r"\b(" + "|".join(re.escape(a) for a in _ABBREVIATIONS) + r")\.",
        r"\1<DOT>",
        masked,
        flags=re.IGNORECASE,
    )


def split_sentences(text: str) -> list[str]:
    """Делит текст на предложения, не разрывая сокращения и инициалы.

    Простое деление по ``[.!?]`` ломало заказы: «…запросов (см. прикрепленный
    файл)» превращалось в два «предложения», и в письмо попадал обрывок
    «прикрепленный файл) эту страницу». Точка после «см», «т. е.», «руб»
    предложение не заканчивает.
    """
    prepared = _mask_abbreviations(text)
    parts = re.split(r"(?<=[.!?])\s+", prepared)
    return [part.replace("<DOT>", ".").strip() for part in parts if part.strip()]


def lowercase_sentence_starts(text: str) -> list[str]:
    """Начала предложений, которые начинаются со строчной буквы.

    Работает поверх :func:`split_sentences`, поэтому точка после сокращения
    («см.», «т. е.», «руб.») не считается концом предложения.
    """
    sentences = split_sentences(text)
    result: list[str] = []
    for sentence in sentences[1:]:
        if not re.match(r"[а-яё]", sentence):
            continue
        # «т.к.», «т.е.» в начале — сокращение, а не небрежность.
        if re.match(r"^[а-яё]\.\s*[а-яё]\.", sentence):
            continue
        result.append(sentence)
    return result
