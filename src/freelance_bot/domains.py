_GENERIC_APPROACH = "Разберусь в задаче, предложу план работ и оценку по срокам"


#: Во сколько раз первый смысловой отрезок заголовка важнее остального.
#: В русском суть работы называет первое существительное: «Тексты для сайта»
#: — это тексты, хотя слово «сайт» в заголовке тоже есть.
_HEAD_WEIGHT = 10


def _head(title: str, words: int = 2) -> str:
    """Первые *words* слов заголовка без пунктуации."""
    tokens = [t for t in title.replace(",", " ").split() if t]
    return " ".join(tokens[:words])


def _score_domain(job: Job, terms: tuple[str, ...]) -> int:
    """Сумма баллов области.

    Заголовок важнее тегов, теги важнее описания. Отдельно взвешивается
    начало заголовка: «Тексты для сайта» и «Разработка сайта с текстами» —
    разные работы, хотя набор слов почти совпадает.
    """
    title = (job.title or "").lower()
    description = _without_negations((job.description or "").lower())
    extras = " ".join([job.category or "", *job.skills]).lower()

    score = 0
    if matching_terms(_head(title), list(terms)):
        score += _HEAD_WEIGHT
    if matching_terms(title, list(terms)):
        score += 6
    if matching_terms(extras, list(terms)):
        score += 3
    if matching_terms(description, list(terms)):
        score += 1
    return score


#: Обороты, которыми заказчик отказывается от канала связи. Заказ на SEO
#: заканчивался «на почту и в телеграм просьба не писать» — и Telegram
#: становился областью заказа, а письмо предлагало команды бота.
_NEGATION_RE = re.compile(
    r"(?:не\s+(?:писать|пишите|звонить|звоните|беспокоить|обращаться)|"
    r"просьба\s+не|не\s+нужно|не\s+требуется|не\s+надо|без\s+звонков)",
    re.IGNORECASE,
)


def _without_negations(description: str) -> str:
    """Убирает из описания предложения с отказами от канала связи."""
    sentences = split_sentences(description)
    kept = [s for s in sentences if not _NEGATION_RE.search(s)]
    return " ".join(kept)


def detect_domain(job: Job) -> tuple[str | None, str]:
    """Возвращает (область, подход) для заказа.

    Область с наибольшим числом баллов; при равенстве побеждает более узкая
    (порядок `DOMAIN_TERMS`), а заголовок всегда перевешивает описание.
    """
    best_domain: str | None = None
    best_score = 0
    for domain, terms in DOMAIN_TERMS.items():
        score = _score_domain(job, terms)
        if score > best_score:
            best_domain, best_score = domain, score

    if best_domain is None:
        category = (job.category or "").lower()
        if "дизайн" in category:
            best_domain = "design"
        elif "текст" in category or "перевод" in category:
            best_domain = "text"

    if best_domain is None:
        return None, _GENERIC_APPROACH
    return best_domain, DOMAIN_APPROACH[best_domain]


def mentioned_domains(text: str) -> set[str]:
    """Области, явно упомянутые в тексте письма."""
    lowered = (text or "").lower()
    found: set[str] = set()
    for domain, terms in DOMAIN_TERMS.items():
        if matching_terms(lowered, list(terms)):
            found.add(domain)
    return found


def _exclusive_domains_mentioned(text: str) -> set[str]:
    """Только «сильные» слова о работе: по ним видно, о чём письмо.

    Общие слова («сайт», «бот») сюда не входят: заказ на сбор базы упоминает
    сайты компаний, и такое письмо — всё равно про парсинг, а не про вёрстку.
    """
    lowered = (text or "").lower()
    found: set[str] = set()
    for domain, terms in EXCLUSIVE_TERMS.items():
        if matching_terms(lowered, list(terms)):
            found.add(domain)
    return found


def wrong_domain_note(message: str, job: Job) -> str | None:
    """Возвращает причину, если письмо говорит не о той работе.

    Проверяются только взаимоисключающие области. Если заказ на сайт, а в
    письме обещан Telegram-бот (и про сайт ни слова) — это ошибка, которую
    нужно переписать. Упоминание обеих областей допустимо: «сайт с ботом».

    Сравниваются сильные слова о работе, а не все маркеры области: заказ на
    сбор базы банных комплексов упоминает сайты компаний, и письмо «проверю
    сайты, соцсети и телефоны» — про парсинг, а не про вёрстку. Раньше такие
    письма блокировались как «не о том» и уходили в шаблон.
    """
    job_domain, _ = detect_domain(job)
    if job_domain not in EXCLUSIVE_DOMAINS:
        return None

    job_terms = EXCLUSIVE_TERMS[job_domain]
    if matching_terms((message or "").lower(), list(job_terms)):
        return None

    mentioned = _exclusive_domains_mentioned(message)
    for other in EXCLUSIVE_DOMAINS:
        if other in mentioned:
            return (
                f"письмо не о том: заказ про «{job_domain}», "
                f"а в тексте речь про «{other}»"
            )
    return None
